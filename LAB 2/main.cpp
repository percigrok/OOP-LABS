#include "Book.h"
#include <iostream>
 
/**
 * @brief Главная функция - полное тестирование класса Book
 * 
 * Этапы тестирования:
 * 1. Создание объектов с использованием различных конструкторов
 * 2. Вывод начального состояния
 * 3. Выполнение корректных операций
 * 4. Выполнение некорректных операций (проверка инвариантов)
 * 5. Повторный вывод состояния
 * 6. Проверка независимости объектов
 */
int main() {
    setlocale(LC_ALL, ".UTF-8");
    
    std::cout << "===== ТЕСТИРОВАНИЕ КЛАССА BOOK =====\n\n";
    
    // === ЭТАП 1: Создание объектов ===
    std::cout << "ЭТАП 1: Создание объектов\n";
    std::cout << "===========================\n";
    
    // Объект 1: конструктор по умолчанию
    Book book1;
    std::cout << "Создана книга book1 (конструктор по умолчанию)\n";
    
    // Объект 2: параметризованный конструктор
    Book book2("Война и мир", "Лев Толстой", 1200);
    std::cout << "Создана книга book2 (параметризованный конструктор)\n";
    
    // Объект 3: параметризованный конструктор со списком инициализации
    Book book3("Преступление и наказание", "Федор Достоевский", 671, false);
    std::cout << "Создана книга book3 (конструктор со списком инициализации)\n";
    
    std::cout << "\nОбщее количество книг: " << Book::getTotalBooks() << "\n\n";

    // === ЭТАП 2: Вывод начального состояния ===
    std::cout << "ЭТАП 2: Вывод начального состояния\n";
    std::cout << "====================================\n";
    book1.print();
    book2.print();
    book3.print();

    // === ЭТАП 3: Выполнение корректных операций ===
    std::cout << "\nЭТАП 3: Выполнение корректных операций\n";
    std::cout << "========================================\n";
    
    std::cout << "\n[КОРРЕКТНАЯ операция] Выдача книги book2...\n";
    if (book2.borrowBook()) {
        std::cout << "Книга успешно выдана!\n";
    } else {
        std::cout << "Ошибка: не удалось выдать книгу\n";
    }
    book2.print();
    
    std::cout << "\n[КОРРЕКТНАЯ операция] Выдача книги book3...\n";
    if (book3.borrowBook()) {
        std::cout << "Книга успешно выдана!\n";
    } else {
        std::cout << "Ошибка: не удалось выдать книгу\n";
    }
    book3.print();
    
    std::cout << "\n[КОРРЕКТНАЯ операция] Изменение количества страниц book2 (1200 на  1300)...\n";
    if (book2.updatePageCount(1300)) {
        std::cout << "Количество страниц успешно изменено!\n";
    } else {
        std::cout << "Ошибка: не удалось изменить количество страниц\n";
    }
    book2.print();

    // === ЭТАП 4: Выполнение некорректных операций ===
    std::cout << "\nЭТАП 4: Выполнение некорректных операций (проверка инвариантов)\n";
    std::cout << "===================================================================\n";
    
    std::cout << "\n[НЕКОРРЕКТНАЯ операция] Инвариант 2: Повторная выдача уже выданной книги book3...\n";
    if (book3.borrowBook()) {
        std::cout << "Книга выдана!\n";
    } else {
        std::cout << "ПЕРЕХВАЧЕНО: Нельзя выдать уже выданную книгу!\n";
    }
    std::cout << "Статус book3 не изменился.\n";
    book3.print();
    
    std::cout << "\n[НЕКОРРЕКТНАЯ операция] Инвариант 3: Возврат невыданной книги book1...\n";
    if (book1.returnBook()) {
        std::cout << "Книга возвращена!\n";
    } else {
        std::cout << "ПЕРЕХВАЧЕНО: Нельзя вернуть книгу, которая не была выдана!\n";
    }
    std::cout << "Статус book1 не изменился.\n";
    book1.print();
    
    std::cout << "\n[НЕКОРРЕКТНАЯ операция] Инвариант 1: Попытка установить отрицательное число страниц...\n";
    if (book1.updatePageCount(-100)) {
        std::cout << "Ошибка: число страниц было изменено на отрицательное!\n";
    } else {
        std::cout << "ПЕРЕХВАЧЕНО: Нельзя установить отрицательное число страниц!\n";
    }
    std::cout << "Статус book1 не изменился.\n";
    
    std::cout << "\n[НЕКОРРЕКТНАЯ операция] Инвариант 1: Попытка установить нулевое число страниц...\n";
    if (book1.updatePageCount(0)) {
        std::cout << "Ошибка: число страниц было изменено на ноль!\n";
    } else {
        std::cout << "ПЕРЕХВАЧЕНО: Нельзя установить нулевое число страниц!\n";
    }
    std::cout << "Статус book1 не изменился.\n";

    // === ЭТАП 5: Повторный вывод состояния ===
    std::cout << "\n\nЭТАП 5: Повторный вывод состояния (проверка сохранения инвариантов)\n";
    std::cout << "=====================================================================\n";
    std::cout << "\nПосле попыток некорректных операций объекты остались в корректном состоянии:\n\n";
    std::cout << "book1 (после попыток изменить):\n";
    book1.print();
    std::cout << "book2 (после успешного обновления на 1300 страниц):\n";
    book2.print();
    std::cout << "book3 (остался в исходном состоянии):\n";
    book3.print();

    // === ЭТАП 6: Проверка независимости объектов ===
    std::cout << "\nЭТАП 6: Проверка независимости объектов\n";
    std::cout << "==========================================\n";
    
    std::cout << "\n[ДО ИЗМЕНЕНИЯ] Состояние книг:\n";
    std::cout << "book1: " << book1.getTitle() << " (" << book1.getPageCount() << " стр.)\n";
    std::cout << "book2: " << book2.getTitle() << " (" << book2.getPageCount() << " стр.)\n";
    std::cout << "book3: " << book3.getTitle() << " (" << book3.getPageCount() << " стр.)\n";
    
    std::cout << "\n[ДЕЙСТВИЕ] Меняем только book1: updatePageCount(250)...\n";
    book1.updatePageCount(250);
    
    std::cout << "\n[ПОСЛЕ ИЗМЕНЕНИЯ] Состояние книг:\n";
    std::cout << "book1: " << book1.getTitle() << " (" << book1.getPageCount() << " стр.) <- ИЗМЕНИЛСЯ\n";
    std::cout << "book2: " << book2.getTitle() << " (" << book2.getPageCount() << " стр.) <- НЕ ИЗМЕНИЛСЯ\n";
    std::cout << "book3: " << book3.getTitle() << " (" << book3.getPageCount() << " стр.) <- НЕ ИЗМЕНИЛСЯ\n";
    
    std::cout << "\nПОДТВЕРЖДЕНО: Изменение book1 не повлияло на book2 и book3\n";
    
    std::cout << "\n\nОбщее количество книг в конце программы: " << Book::getTotalBooks() << "\n";
    std::cout << "\n===== КОНЕЦ ТЕСТИРОВАНИЯ =====\n";
    
    return 0;
}